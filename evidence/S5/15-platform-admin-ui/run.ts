const server = await startControlPlaneServer({ dbPath: join(root, 'control.sqlite'), dataDir: join(root, 'data'), port: 0, sessionSecret: 'platform-admin', platformAdminToken: 'platform-secret' })
const browser = await chromium.launch({ headless: true, executablePath: '/root/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome', args: ['--no-sandbox'] })
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } })
  const errors: string[] = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', error => errors.push(String(error)))
  await page.goto(`${server.url}/admin`, { waitUntil: 'domcontentloaded' })
  await page.getByPlaceholder('X-SiriusX-Platform-Token').fill('platform-secret')
  await page.getByRole('button', { name: 'Load' }).click()
  await page.waitForTimeout(300)
  await page.getByPlaceholder('Display name').fill('Model UI')
  await page.getByPlaceholder('Provider', { exact: true }).fill('openai')
  await page.getByPlaceholder('Provider model id').fill('gpt-ui')
  await page.getByRole('button', { name: 'Add model' }).click()
  await page.waitForTimeout(400)
  await page.getByPlaceholder('Name', { exact: true }).fill('Platform Tenant')
  await page.getByPlaceholder('IdP issuer').fill('https://idp.platform.example')
  await page.getByPlaceholder('Admin email').fill('admin@platform.example')
  await page.getByPlaceholder('Tenant id (optional)').fill('tenant-platform')
  await page.getByRole('button', { name: 'Create' }).click()
  await page.waitForTimeout(500)
  await page.getByPlaceholder('provider', { exact: true }).fill('gitlab')
  await page.getByPlaceholder('external id', { exact: true }).fill('acme/webhook')
  await page.getByPlaceholder('tenant id', { exact: true }).fill('tenant-platform')
  await page.getByRole('button', { name: 'Add source binding' }).click()
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Suspend' }).last().click()
  await page.waitForTimeout(400)
  const suspended = (await page.locator('body').innerText()).includes('suspended')
  await page.getByRole('button', { name: 'Resume' }).last().click()
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Users' }).first().click()
  await page.waitForTimeout(300)
  await page.getByRole('button', { name: 'Bind' }).last().click()
  await page.waitForTimeout(400)
  await page.getByRole('button', { name: 'Set default' }).last().click()
  await page.waitForTimeout(300)
  await page.getByPlaceholder('Cloud ticket cents').fill('10')
  await page.getByRole('button', { name: 'Save billing' }).click()
  await page.waitForTimeout(300)
  await page.getByPlaceholder('Tenant name').fill('Platform Tenant 2')
  await page.getByRole('button', { name: 'Save tenant' }).click()
  await page.waitForTimeout(400)
  await page.getByPlaceholder('Max users').fill('2')
  await page.getByRole('button', { name: 'Save quota' }).click()
  await page.waitForTimeout(300)
  await page.getByPlaceholder('User email').fill('member@platform.example')
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.waitForTimeout(500)
  const body = await page.locator('body').innerText()
  await page.screenshot({ path: '/root/siriusx/evidence/S5/15-platform-admin-ui/admin.png', fullPage: true })
  const result = { tenant: body.includes('tenant-platform'), suspended, usage: body.includes('Platform Tenant 2'), quota: body.includes('Quota') && body.includes('Save quota'), usageDaily: body.includes('Usage (14d)'), source: body.includes('acme/webhook'), billing: body.includes('Billing') && body.includes('Estimate:'), model: body.includes('Model UI') && body.includes('Catalog models'), audit: body.includes('Platform audit') && body.includes('tenant.create'), platformExport: body.includes('Export CSV'), user: body.includes('member@platform.example'), errors }
  console.log(JSON.stringify(result, null, 2))
  if (!result.tenant || !result.suspended || !result.usage || !result.quota || !result.usageDaily || !result.source || !result.billing || !result.model || !result.audit || !result.platformExport || !result.user || errors.length > 0) process.exitCode = 1
} finally {
  await browser.close(); await server.close(); await rm(root, { recursive: true, force: true })
}
