import { chromium } from '/root/siriusx/deepseek-harness/node_modules/.pnpm/playwright@1.61.1/node_modules/playwright/index.mjs'
const browser = await chromium.launch({ headless: true, executablePath: '/root/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome', args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1400, height: 900 } })
await context.addInitScript(({ token }) => {
  try { localStorage.setItem('siriusx.controlToken', token); localStorage.setItem('siriusx.controlApi', 'http://127.0.0.1:4321') } catch {}
}, { token: process.env.TOKEN })
const page = await context.newPage()
const errors = []
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.on('pageerror', error => errors.push(String(error)))
await page.goto(process.env.DSH_URL, { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(4500)
const cont = page.getByRole('button', { name: 'Continue' }); if (await cont.count()) await cont.click()
await page.waitForTimeout(700)
const team = page.locator('button[aria-label="Team"]'); if (await team.count()) await team.first().click()
await page.waitForTimeout(1200)
await page.getByRole('button', { name: 'devices' }).click()
await page.waitForTimeout(700)
const before = await page.locator('body').innerText()
await page.getByRole('button', { name: 'Rotate token' }).first().click()
await page.waitForTimeout(1000)
const after = await page.locator('body').innerText()
await page.getByRole('button', { name: 'Revoke' }).first().click()
await page.waitForTimeout(800)
const revoked = await page.locator('body').innerText()
await page.screenshot({ path: '/root/siriusx/evidence/S5/09-device-ui/devices.png', fullPage: true })
await context.close(); await browser.close()
const result = { hasDevices: before.includes('Devices'), hasDevice: before.includes('iPhone'), rotated: after.includes('New token (shown once)'), revoked: revoked.includes('revoked'), errors }
console.log(JSON.stringify(result, null, 2))
if (!result.hasDevices || !result.hasDevice || !result.rotated || !result.revoked) process.exit(1)
