import { chromium } from '/root/siriusx/deepseek-harness/node_modules/.pnpm/playwright@1.61.1/node_modules/playwright/index.mjs'
const browser = await chromium.launch({ headless: true, executablePath: '/root/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } })
const errors = []
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.on('pageerror', error => errors.push(String(error)))
await page.goto('http://127.0.0.1:8091/', { waitUntil: 'domcontentloaded' })
await page.getByPlaceholder('X-SiriusX-Platform-Token').fill('platform-secret')
await page.getByRole('button', { name: 'Load' }).click()
await page.waitForTimeout(500)
await page.getByPlaceholder('Name', { exact: true }).fill('Standalone Tenant')
await page.getByPlaceholder('IdP issuer').fill('https://idp.standalone.example')
await page.getByPlaceholder('Admin email').fill('admin@standalone.example')
await page.getByPlaceholder('Tenant id (optional)').fill('tenant-standalone')
await page.getByRole('button', { name: 'Create tenant' }).click()
await page.waitForTimeout(800)
await page.getByRole('button', { name: 'Open' }).last().click()
await page.waitForTimeout(700)
const body = await page.locator('body').innerText()
await page.screenshot({ path: '/root/siriusx/evidence/S5/31-admin-web/admin.png', fullPage: true })
await browser.close()
const result = { tenant: body.includes('Standalone Tenant'), config: body.includes('Tenant config'), quota: body.includes('Quota'), billing: body.includes('Billing'), usage: body.includes('Usage (14d)'), audit: body.includes('Audit summary'), errors }
console.log(JSON.stringify(result, null, 2))
if (!result.tenant || !result.config || !result.quota || !result.billing || !result.usage || !result.audit || errors.length > 0) process.exit(1)
