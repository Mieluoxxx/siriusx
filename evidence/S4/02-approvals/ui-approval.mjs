await page.getByRole('button',{name:'approvals'}).click(); await page.waitForTimeout(1000)
const before=await page.locator('body').innerText()
await page.getByRole('button',{name:'Approve'}).click(); await page.waitForTimeout(2500)
const after=await page.locator('body').innerText()
console.log(JSON.stringify({before:before.slice(0,1400),after:after.slice(0,1400),errors},null,2))
await page.screenshot({path:'/tmp/s6-ui-approval.png',fullPage:true})
