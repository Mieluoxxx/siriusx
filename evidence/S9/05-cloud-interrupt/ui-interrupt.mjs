import { chromium } from '/root/siriusx/deepseek-harness/node_modules/.pnpm/playwright@1.61.1/node_modules/playwright/index.mjs'
const browser = await chromium.launch({ headless: true, executablePath: '/root/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome', args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1400, height: 900 } })
const login = await context.request.post('http://127.0.0.1:8080/auth/session', { data: { token: process.env.TOKEN } })
if (login.status() !== 204) throw new Error(`login failed: ${login.status()}`)
await context.addInitScript(() => { try { localStorage.setItem('siriusx.gatewayAuth', '1') } catch {} })
const page = await context.newPage()
const errors = []; page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) }); page.on('pageerror', e => errors.push(String(e)))
await page.goto('http://127.0.0.1:8080/', { waitUntil: 'domcontentloaded' }); await page.waitForTimeout(6000)
const cont = page.getByRole('button', { name: 'Continue' }); if (await cont.count()) await cont.click(); await page.waitForTimeout(800)
const team = page.locator('button[aria-label="Team"]'); if (await team.count()) await team.first().click(); await page.waitForTimeout(1000)
await page.getByPlaceholder('Cloud repository URL').fill('https://github.com/acme/slow-repo.git')
await page.getByPlaceholder('Base ref').fill('main')
await page.getByPlaceholder('What should the bot do?').fill('cloud task to interrupt')
await page.getByRole('button', { name: 'Dispatch cloud ticket' }).click()
await page.waitForTimeout(4000)
const before = await page.locator('body').innerText()
await page.getByRole('button', { name: 'Stop' }).click()
await page.waitForTimeout(3000)
const after = await page.locator('body').innerText()
console.log(JSON.stringify({ before: before.slice(0, 1200), after: after.slice(0, 1600), errors }, null, 2))
await page.screenshot({ path: '/tmp/s9-cloud-interrupt.png', fullPage: true })
await browser.close()
